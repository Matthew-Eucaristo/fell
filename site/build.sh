#!/usr/bin/env bash
# Assembles the GitHub Pages site into _site/ (or the directory given).
# Run from the repository root: site/build.sh [outdir]
# The interactive demo on the page is fed by fell itself: this script builds
# the dummy workspace from demo/setup.sh in a throwaway directory (fake HOME,
# one fake repository, worktrees left by fake agents) and records fell's
# read-only output on it into sample.js: `fell scan --json`, `fell --list`
# and `fell capabilities --json`. Nothing else is run: no strip, retire or
# apply, and never against a real HOME. The recording is converted from
# demo/demo.gif; without ffmpeg the page falls back to the GIF itself.
set -euo pipefail
out=${1:-_site}
tmp=$(cd "$(mktemp -d)" && pwd -P) # canonical, so fell prints ~/ paths
demo="$tmp/demo"
cleanup() {
  if [ -s "$tmp/live.pid" ]; then kill "$(cat "$tmp/live.pid")" 2>/dev/null || true; fi
  if command -v hdiutil >/dev/null && [ -d "$demo/home" ]; then hdiutil detach -quiet "$demo/home" 2>/dev/null || true; fi
  chmod -R u+w "$tmp" 2>/dev/null || true
  rm -rf "$tmp"
}
trap cleanup EXIT

rm -rf "$out"
mkdir -p "$out"
cp site/index.html site/style.css site/app.js site/favicon.svg site/og.png \
   site/404.html site/robots.txt site/sitemap.xml "$out"/
cp demo/demo.gif "$out"/demo.gif

# The dummy workspace, exactly as the recording uses it. setup.sh builds
# fell, sets HOME to the fake one and starts the "live" session (a sleep).
# TMPDIR points inside the workspace too, so no agent location outside it
# is read.
FELL_DEMO_DIR="$demo" OUT="$tmp" bash -c '
  source demo/setup.sh >/dev/null
  echo "$FELL_DEMO_LIVE" >"$OUT/live.pid"
  export TMPDIR="$DEMO/tmp" && mkdir -p "$TMPDIR"
  fell scan --json >"$OUT/scan.json"
  fell --list >"$OUT/list.txt"
  fell capabilities --json >"$OUT/caps.json"
'
python3 - "$tmp" "$demo" "$out" <<'PY'
import html, json, re, sys
tmp, demo, out = sys.argv[1:]
scan = json.load(open(f"{tmp}/scan.json"))
caps = json.load(open(f"{tmp}/caps.json"))
listing = open(f"{tmp}/list.txt").read()
text = json.dumps(scan) + json.dumps(caps) + listing
# Only the fake HOME may appear, and only as ~/.
for leak in (demo, tmp, "/Users/", "/home/"):
    if leak in text:
        sys.exit(f"site/build.sh: output contains {leak!r}; refusing to publish it")
if not scan["items"]:
    sys.exit("site/build.sh: the demo scan found no worktrees")
# The TUI's one-line "official way" per owner (Owner.Short) is not part of the
# contract, so it is read from the owner table the binary was built from.
src = open("internal/agents/agents.go").read()
short = dict(re.findall(r'ID: "([a-z0-9-]+)".*?Short: +"((?:[^"\\]|\\.)*)"', src, flags=re.S))
missing = {i["owner"]["id"] for i in scan["items"]} - short.keys()
if missing:
    sys.exit(f"site/build.sh: no Short removal text for owners {sorted(missing)} in internal/agents/agents.go")
with open(f"{out}/sample.js", "w") as f:
    f.write("// Generated by site/build.sh from fell's read-only output on demo/setup.sh's dummy workspace. Not a real machine.\n")
    f.write("window.FELL_SAMPLE = " + json.dumps({"scan": scan, "caps": caps, "list": listing, "short": short}, ensure_ascii=False) + ";\n")
# Static parts of the page that come from the same run.
page = open(f"{out}/index.html").read()
owners = sum(1 for o in caps["owners"] if o["id"] != "git")
fills = {
    "list": html.escape(listing.rstrip("\n")),
    "owners": str(owners),
    "kinds": str(len({a["name"] for a in caps["artifact_kinds"]})),
}
for key, val in fills.items():
    page, n = re.subn(rf"<!--{key}-->.*?<!--/{key}-->", lambda m: val, page, flags=re.S)
    if not n:
        sys.exit(f"site/build.sh: no <!--{key}--> placeholder in index.html")
open(f"{out}/index.html", "w").write(page)
PY

# Latest release tag, when tags are available (CI fetches them).
if tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  sed -i.bak "s|<!--version-->[^<]*<!--/version-->|$tag|" "$out/index.html" && rm -f "$out/index.html.bak"
fi

if command -v ffmpeg >/dev/null; then
  ffmpeg -loglevel error -y -i demo/demo.gif -movflags +faststart -pix_fmt yuv420p \
    -vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" -c:v libx264 -crf 24 -preset slow "$out/demo.mp4"
  ffmpeg -loglevel error -y -i demo/demo.gif -vf "select=eq(n\,100)" -frames:v 1 -c:v libwebp -quality 82 "$out/demo-poster.webp" || true
else
  echo "ffmpeg not found: the page will show demo.gif instead of a video" >&2
fi
ls -la "$out"
